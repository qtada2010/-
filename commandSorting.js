'use strict';
// ==========================================================================
// 🔤 commandSorting.js — مصدر وحيد لترتيب الأوامر أبجدياً في كل واجهات البوت
//
// لماذا هذا الملف موجود؟
// كانت الأوامر تُعرض بترتيب كتابتها في الكود، أي ترتيب عشوائي من وجهة نظر
// المستخدم. فمن يفتح صفحة الأوامر لا يعرف أين يبحث عن أمر معيّن. هذا الملف
// يوفّر مقارنات ثابتة تُستخدم في كل مكان، فيصبح الترتيب متوقَّعاً وموحّداً:
// نفس الأمر في نفس المكان، في صفحة اللوحة ودليل الأوامر وقائمة المساعدة.
//
// ⚠️ ملاحظة مهمة: هذا الملف يرتّب العرض فقط. لا يغيّر أي سلوك ولا يفعّل أو
// يعطّل أي أمر، ولا يلمس أسماء الأوامر أو اختصاراتها.
// ==========================================================================

// الرموز التعبيرية وعلامات التنسيق التي تتصدّر بعض العناوين (مثل «💰 حاسبة الضريبة»).
// نتجاهلها عند الترتيب حتى لا تتقدّم البطاقات ذات الإيموجي على غيرها عشوائياً.
const LEADING_DECORATION = /^[\s\p{Extended_Pictographic}\p{Emoji_Presentation}\uFE0F\u200D\u2190-\u21FF\u2600-\u27BF·•\-—_]+/u;

// التشكيل والعلامات العربية التي لا تؤثر على الترتيب الأبجدي.
const ARABIC_DIACRITICS = /[\u064B-\u0652\u0670\u0640]/g;

/**
 * يحوّل أي عنوان إلى صيغة قابلة للمقارنة:
 *  • يزيل الإيموجي والرموز من البداية
 *  • يوحّد الألف بأشكالها (أ إ آ ٱ → ا) والتاء المربوطة (ة → ه) والألف المقصورة (ى → ي)
 *  • يزيل التشكيل والتطويل
 * بذلك يقع «الإدارة» و«الادارة» في المكان نفسه بدل أن يتفرّقا.
 */
function sortKey(value) {
  return String(value == null ? '' : value)
    .replace(LEADING_DECORATION, '')
    .replace(ARABIC_DIACRITICS, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .trim()
    .toLowerCase();
}

// مقارن واحد يفهم العربية والإنجليزية معاً:
//  • الأسماء الإنجليزية ترتَّب من a إلى z
//  • الأسماء العربية ترتَّب حسب الترتيب الأبجدي العربي
//  • الأرقام داخل الأسماء ترتَّب رقمياً (status2 بعد status وليس قبله)
const collator = new Intl.Collator(['ar', 'en'], { numeric: true, sensitivity: 'base' });

/** يقارن نصين أبجدياً. يُستخدم مباشرة داخل Array.prototype.sort. */
function compareNames(a, b) {
  return collator.compare(sortKey(a), sortKey(b));
}

/**
 * يرتّب مصفوفة أبجدياً حسب مفتاح مستخرَج من كل عنصر، دون تعديل المصفوفة الأصلية.
 * عدم التعديل مقصود: كثير من هذه المصفوفات (مثل commandData) مشتركة بين
 * تسجيل أوامر السلاش والتوجيه، وترتيبها في مكانها قد يغيّر سلوكاً آخر.
 *
 * @param {Array}    items   المصفوفة المراد ترتيبها (تبقى كما هي)
 * @param {Function} getName دالة تُرجع النص الذي يُرتَّب عليه كل عنصر
 * @returns {Array} نسخة مرتّبة
 */
function sortByName(items, getName = item => item) {
  return [...items].sort((a, b) => compareNames(getName(a), getName(b)));
}

module.exports = { compareNames, sortByName, sortKey };
