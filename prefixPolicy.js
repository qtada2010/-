'use strict';
// ==========================================================================
// 🚦 prefixPolicy.js — أي أمر يعمل بالبريفكس وأيها صار سلاش فقط
//
// طلب المالك: «خلّي كل أوامر الإدارة والأونرات والإدارة العليا والأعضاء بسلاش
// فقط بدون بريفكس، حتى $come و$say — وتبقى أوامر التذكرة تعمل كما هي».
//
// القاعدة في مكان واحد، فيعمل بها كل من:
//   • slashPrefix.js   (جسر البريفكس لأوامر السلاش)
//   • messageCreate.js (أوامر $come و$say والضريبة + أوامر التذكرة)
//   • system.js        (أوامر النظام القديمة: !اضافة · !رول · !الحالة …)
//   • xp.js            (أوامر الإكسبي العربية القديمة)
//   • clans.js         (أوامر الكلانات القديمة)
//
// المعيار: كل أمر له صيغة سلاش ⇒ صار يعمل بالسلاش فقط. أما أوامر التذكرة
// (إغلاق · حفظ · حذف · إضافة · إزالة · إعادة تسمية) وسجل الاستلام فتبقى
// بالبريفكس كما هي. والاختصار المجرّد (بلا بريفكس) يبقى يعمل لأن المالك
// هو من كتبه بنفسه — المحذوف هو البريفكس لا الاختصار.
// ==========================================================================

const { SLASH_COMMAND_NAMES } = require('./slashCommandConfig');

// 🎫 استثناء المالك: هذه تبقى بالبريفكس (أوامر التذكرة + سجل الاستلام)
const PREFIX_KEPT = Object.freeze([
  'close', 'save', 'delete', 'add', 'remove', 'rename',
  'claim', 'استلام'
]);

// 🕰️ أسماء أوامر النظام/الإكسبي/الكلانات القديمة التي صار لها سلاش
const SYSTEM_SLASH_ONLY = Object.freeze([
  // صلاحيات الروم
  'اضافة', 'add', 'كتابة', 'write',
  // رومات الضريبة والاقتراحات
  'ضريبة', 'tax-channel', 'اقتراحات', 'set-suggestions',
  // تغيير اسم الروم
  'r',
  // رول / حالة البوت
  'رول', 'الحالة', 'status', 'الحالة2', 'status2',
  // سجل الأخطاء
  'logowner',
  // الكلانات
  'كلان', 'تقديم-كلان',
  // الإكسبي
  'اضافة-اكسبي', 'سحب-اكسبي',
  'اضافة-اكسبي-يومي', 'سحب-اكسبي-يومي',
  'اضافة-اكسبي-اسبوعي', 'سحب-اكسبي-اسبوعي',
  'اضافة-اكسبي-شهري', 'سحب-اكسبي-شهري',
  'معلوماتي'
]);

const SLASH_ONLY = new Set(SLASH_COMMAND_NAMES.map(name => String(name).toLowerCase()));
const KEPT = new Set(PREFIX_KEPT);
const SYSTEM_ONLY = new Set(SYSTEM_SLASH_ONLY.map(name => String(name).toLowerCase()));

/**
 * هل هذا الأمر ممنوع بالبريفكس؟ (اسم أمر سلاش أو أمر نظام قديم صار له سلاش)
 * أوامر التذكرة وسجل الاستلام مستثناة دائماً.
 */
function isPrefixBlocked(name) {
  const key = String(name || '').trim().toLowerCase();
  if (!key || KEPT.has(key)) return false;
  return SLASH_ONLY.has(key) || SYSTEM_ONLY.has(key);
}

module.exports = {
  PREFIX_KEPT,
  SYSTEM_SLASH_ONLY,
  isPrefixBlocked
};
