// ==========================================================================
// 📦 storedJson.js — قراءة قيمة إعداد محفوظة في bot_settings
//
// لماذا هذا الملف موجود؟
// كل إعدادات الأوامر تُخزَّن في عمود واحد: bot_settings.value، ونوعه JSONB
// في القواعد الحديثة. لكن عموداً أُنشئ في نسخ قديمة من المشروع كان **نصاً**
// (TEXT)، و«CREATE TABLE IF NOT EXISTS» لا يغيّر نوع عمود قائم. فتعود القيمة
// من قاعدة البيانات نصاً لا كائناً، فتراها مطبّعات الإعدادات (normalize…)
// كائناً فارغاً فتُسقطها إلى القيم الافتراضية:
//
//   • بطاقة الأمر في اللوحة تعرض الافتراضي دائماً، كأن أحداً لم يحفظ شيئاً.
//   • شريط الحفظ يقول «أرسلنا … لكن الخادم أعاد …» بينما الكتابة ناجحة فعلاً.
//   • اختصارات الأوامر والرولات المحفوظة تختفي بلا أي رسالة خطأ.
//
// نفس الاحتمال تتعامل معه أداة diagnoseSaving.js بالسطر:
//   typeof row.value === 'string' ? JSON.parse(row.value) : row.value
// فيجب أن يتعامل معه البوت نفسه أيضاً — لا أداة التشخيص وحدها.
//
// هذا الملف يفعل شيئاً واحداً: يُرجع الكائن كما هو إن كان كائناً، ويحوّل
// النص إلى كائن إن كان نص JSON صالحاً، ويردّ النص كما هو إن لم يكن JSON
// صالحاً حتى تتعامل معه المطبّعات كقيمة غير صالحة بلا رمي خطأ.
// ==========================================================================

function parseStoredJson(value) {
  if (typeof value !== 'string') return value;
  try {
    return JSON.parse(value);
  } catch (error) {
    return value;
  }
}

module.exports = { parseStoredJson };
