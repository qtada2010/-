'use strict';

// ============================================================================
// كشف تعدّد النسخ من داخل المتصفح
//
// حين لا نستطيع الوصول إلى خادم المالك، تبقى الصفحة نفسها أفضل أداة قياس.
// بعد كل حفظ تُعاد قراءة الصفحة؛ فإن جاءت من عملية غير التي كتبنا إليها
// فالسبب ليس في الكود بل في تشغيل أكثر من نسخة، ويجب أن نقولها صراحةً
// بدل أن نترك المالك يطارد عطلاً غير موجود.
//
// BUILD_ID وحدها لا تكفي: نسختان من نفس الكود لهما البصمة ذاتها. لذلك
// أُضيف INSTANCE_ID العشوائي، وهذه الاختبارات تقفل السلوكين.
// ============================================================================

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const source = fs.readFileSync(path.join(__dirname, 'dashboard.js'), 'utf8');

test('معرّف العملية عشوائي ويُعرض في الصفحة', () => {
  assert.match(source, /const INSTANCE_ID = require\('crypto'\)\.randomBytes\(3\)/,
    'يجب أن يُولَّد معرّف العملية عشوائياً عند كل إقلاع');
  assert.ok(source.includes('data-instance="${INSTANCE_ID}"'),
    'يجب أن يصل معرّف العملية إلى المتصفح في سمة data-instance');
});

test('التحقق يميّز اختلاف البناء عن اختلاف العملية عن فشل الكتابة', () => {
  assert.ok(source.includes("split: 'build'"), 'حالة اختلاف نسخة الكود');
  assert.ok(source.includes("split: 'instance'"), 'حالة تعدّد العمليات بنفس الكود');
  assert.ok(source.includes("report.split === 'build'"), 'رسالة مخصّصة لاختلاف الكود');
  assert.ok(source.includes("report.split === 'instance'"), 'رسالة مخصّصة لتعدّد النسخ');
  assert.ok(source.includes('(بلا أثر للكتابة)'), 'رسالة مخصّصة لفشل الكتابة');
});

// ============================================================================
// «الخادم أعاد قيمة مختلفة» ليس دليل فشل الكتابة
//
// الخادم يطبّع قيماً كثيرة عمداً: اختصار مكرر، اختصار يساوي اسم الأمر نفسه،
// فراغات، حالة أحرف، نص أطول من حدّ ديسكورد. وكان كل تطبيع منها يُعرض للمالك
// كأن الحفظ لم يثبت — وهو ناجح. الفرق الوحيد الذي يعني فشلاً حقيقياً هو أن
// تعود القيمة **كما كانت قبل الحفظ**، أي بلا أثر للكتابة.
//
// هذه الاختبارات تقفل التمييز حتى لا يعود الخطأ المربك.
// ============================================================================

test('التمييز بين القيمة الضائعة والقيمة التي طبّعها الخادم قائم', () => {
  assert.ok(source.includes('report.lost.length'),
    'يجب وجود مسار مخصّص للقيمة التي لم يظهر لها أثر');
  assert.ok(source.includes('previousComparable === theirs'),
    'الضياع يُحكم عليه بمقارنة ما أعاده الخادم بما كان قبل الحفظ');
  assert.ok(source.includes('snapshot.get(form)'),
    'لقطة ما قبل الحفظ هي المرجع، بلا حفظ حالة إضافية');
});

test('القيمة التي طبّعها الخادم تُعرض تطبيعاً لا فشلاً', () => {
  assert.ok(source.includes('وطبّع الخادم'),
    'رسالة منفصلة تخبر المالك أن القيمة رُفضت بقواعد الأمر لا أن الحفظ تعطّل');
  assert.ok(source.includes('bar.classList.add(\'is-done\')'),
    'حالة التطبيع نجاح (is-done) لا خطأ (is-error)');
});

// ============================================================================
// الاختصار ورفضه: حالتان فقط (قرار المالك النهائي)
//
//   1) الاختصار مستخدم مسبقاً في أمر آخر → رسالة تذكر اسم صاحبه.
//   2) أطول من 32 حرفاً.
// وما عدا ذلك مسموح — حتى الاختصار المطابق لاسم الأمر نفسه مثل $help.
// والمقارنة بعد الحفظ تفكّ JSON وتطبّق تطبيع الخادم نفسه.
// ============================================================================

test('المحرّر يرفض في حالتين فقط: التكرار باسم صاحبه، أو الطول', () => {
  assert.ok(source.includes('const ALIAS_MAX = 32'), 'حدّ الطول 32 مطبَّق في المحرّر');
  assert.ok(source.includes("'هذا الاختصار مستخدم في «'"),
    'رسالة التكرار تُبنى من اسم صاحب الاستخدام');
  assert.ok(source.includes("'» سابقاً — اختر اسماً غيره.'"), 'وتذكر أنه مستخدم سابقاً');
  assert.ok(!source.includes('هو اسم الأمر نفسه'), 'لم يعد يُرفض الاختصار المطابق لاسم الأمر');
  assert.ok(!source.includes('الفاصلة (,) غير مسموحة'), 'ولا تُرفض الفاصلة');
  assert.ok(!source.includes('المسافة غير مسموحة'), 'ولا تُرفض المسافة');
});

test('المقارنة بعد الحفظ تفكّ JSON الاختصارات وتطبّعها كالخادم', () => {
  assert.ok(source.includes('data-alias-editor'),
    'يجب أن تعرف المقارنة أن الحقل اختصارات');
  assert.ok(source.includes('const aliasListOf = raw => {'),
    'تفكّ JSON أو الصيغة القديمة قبل المقارنة');
  assert.ok(source.includes('[...new Set(aliasListOf(value)'), 'وتزيل المكرر وتوحّد الحالة');
});

test('رسالة الفشل تعرض القيمتين لا اسم الحقل وحده', () => {
  // بغير القيمتين يبقى السبب مجهولاً ويضيع وقت المالك في التخمين.
  assert.ok(source.includes("' لكن الخادم أعاد '"),
    'يجب أن تُظهر الرسالة ما أُرسل وما أعاده الخادم');
});

test('عمليتان من نفس الكود تحملان معرّفين مختلفين', () => {
  // نُحاكي ما يفعله المتصفح: يقارن سمة data-instance بين صفحتين.
  const crypto = require('crypto');
  const first = crypto.randomBytes(3).toString('hex');
  const second = crypto.randomBytes(3).toString('hex');
  assert.notStrictEqual(first, second,
    'لو تطابقا لما استطاع المتصفح كشف تعدّد النسخ');
  assert.match(first, /^[0-9a-f]{6}$/);
});
